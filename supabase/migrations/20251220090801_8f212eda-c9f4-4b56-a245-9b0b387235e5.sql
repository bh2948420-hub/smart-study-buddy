-- Create curriculum_context table to store uploaded curriculum files for AI context
CREATE TABLE public.curriculum_context (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    file_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    content_text TEXT,
    subject TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.curriculum_context ENABLE ROW LEVEL SECURITY;

-- RLS Policies
CREATE POLICY "Users can view their own curriculum" ON public.curriculum_context
    FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can insert their own curriculum" ON public.curriculum_context
    FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete their own curriculum" ON public.curriculum_context
    FOR DELETE USING (auth.uid() = user_id);

-- Create schedule table for study schedule
CREATE TABLE public.study_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    subject TEXT NOT NULL,
    day_of_week INTEGER NOT NULL CHECK (day_of_week >= 0 AND day_of_week <= 6),
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    classroom TEXT,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Enable RLS
ALTER TABLE public.study_schedule ENABLE ROW LEVEL SECURITY;

-- RLS Policies
