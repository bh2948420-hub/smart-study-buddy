-- Create indexes
CREATE INDEX idx_curriculum_context_user ON public.curriculum_context(user_id);
CREATE INDEX idx_study_schedule_user_day ON public.study_schedule(user_id, day_of_week);
CREATE INDEX idx_notifications_user_unread ON public.notifications(user_id, is_read);
